"""BEHAVIOR-1K 2026-challenge tasks (all 100; checked-in metadata; no dataset import).

``tasks.json`` is generated by ``scripts/generate_behavior_tasks.py`` from the pinned
2026 task-instance metadata and the upstream challenge gallery. Layout collections:
0 = train instances (exploration), 1 = public test instances 301-320 (held out).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

TASKS_FILE = Path(__file__).with_name("tasks.json")
EXPLORATION_COLLECTION, FORMAL_COLLECTION = 0, 1
PUBLIC_TEST_INSTANCE_IDS = tuple(range(301, 321))
# Official timeout: EVAL_TIMEOUT_MULTIPLIER x mean human demo length (30 Hz frames).
EVAL_TIMEOUT_MULTIPLIER = 1.5


@lru_cache(maxsize=1)
def _catalog():
    return json.loads(TASKS_FILE.read_text())


def task_names():
    return sorted(_catalog()["tasks"])


def task_info(task):
    tasks = _catalog()["tasks"]
    if task not in tasks:
        raise ValueError(f"Unknown or unsupported BEHAVIOR task: {task!r}; supported: {', '.join(sorted(tasks))}")
    return dict(tasks[task])


def native_step_limit(task):
    return int(task_info(task)["human_mean_length_steps"] * EVAL_TIMEOUT_MULTIPLIER)


def instance_ids(task, collection):
    """Instance IDs available in a layout collection, in canonical order."""
    info = task_info(task)
    if collection == EXPLORATION_COLLECTION:
        first, last = info["train_instance_range"]
        return tuple(range(first, last + 1))
    if collection == FORMAL_COLLECTION:
        return PUBLIC_TEST_INSTANCE_IDS
    raise ValueError("BEHAVIOR layout collections are 0 (train) and 1 (public test)")


def layout_instance(task, collection, layout_id):
    """Map a harness layout id to a BEHAVIOR instance id.

    Exploration cycles through the train instances (layout ids wrap around); formal layout
    ids index the 20 held-out public test instances and never wrap.
    """
    ids = instance_ids(task, collection)
    if not isinstance(layout_id, int) or isinstance(layout_id, bool) or layout_id < 0:
        raise ValueError(f"layout ids are nonnegative integers, got {layout_id!r}")
    if collection == EXPLORATION_COLLECTION:
        return ids[layout_id % len(ids)]
    if layout_id >= len(ids):
        raise ValueError(f"layout {layout_id} is outside held-out collection {collection} (0..{len(ids) - 1}) for {task}")
    return ids[layout_id]


def validate_layouts(task, collection, layout_ids):
    for layout_id in layout_ids:
        layout_instance(task, collection, layout_id)


# Environment creation deadline, calibrated by scripts/behavior_doctor.py (see docs/BEHAVIOR_BACKEND.md).
STARTUP_SECONDS = 900


def task_timeouts(task):
    """An episode ends at its native step limit: it has no wall-clock limit (episode_seconds None)."""
    return {"native_step_limit": native_step_limit(task), "episode_seconds": None, "startup_seconds": STARTUP_SECONDS}
